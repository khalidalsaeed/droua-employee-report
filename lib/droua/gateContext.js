/* ─── سياق البوابة: حارسٌ لا يُنسى ─────────────────────────────────────
   =========================================================================
   السؤال الذي تجيب عنه هذه الوحدة: كيف نضمن أن **كل** مسار مستقبليّ يلمس
   ملفّات القسم مرّ بالبوابة أوّلًا؟

   الجواب المعتاد — «سنتذكّر أن نضع الحارس في أوّل كل موجّه» — يفشل بصمت:
   المسار الذي يُنسى فيه الحارس يعمل تمامًا، ويُرجع الملفّ، ولا يُصدر خطأً.
   والاختبار الذي يقرأ الشيفرة نصًّا يمسك الشكل المتوقَّع وحده، ويعمى عن
   استدعاءٍ غير مباشر.

   فبدل ذلك: الوصول إلى الملفّات **يقع داخل سياق** يفتحه الحارس وحده. ومن
   يستدعي files.js خارجه يأخذ استثناءً في السطر الأول — في CI قبل الإنتاج.

   AsyncLocalStorage يحمل السياق عبر await دون تمريره وسيطًا في كل دالّة،
   فلا سبيل إلى تزويره من الطلب: لا ترويسة تفتحه، ولا حقل في الجسم. */

const { AsyncLocalStorage } = require("node:async_hooks");

const storage = new AsyncLocalStorage();

/* يفتحه الحارس بعد التحقّق من هويّة المستخدم **ومن جلسة بوابة حيّة** معًا.
   ولا يُصدَّر إلى خارج القسم. */
function runWithGate({ userId, sidHash }, fn) {
  if (!userId) throw new Error("سياق البوابة يحتاج هويّة");
  return storage.run(Object.freeze({ userId, sidHash: sidHash || null, at: Date.now() }), fn);
}

function current() {
  return storage.getStore() || null;
}

/* تُنادى في مستهلّ كل دالّة تلمس ملفّات القسم. */
function requireGate() {
  const ctx = storage.getStore();
  if (!ctx) throw new Error("لا سياق بوابة — الوصول إلى ملفّات القسم يمرّ بالحارس");
  return ctx;
}

module.exports = { runWithGate, current, requireGate };
