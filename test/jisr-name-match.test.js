const test = require("node:test");
const assert = require("node:assert/strict");

const {
  similarity, foldArabic, nameTokens, tokenMatch, assignOneToOne,
  DECIDED_MIN_SCORE, DECIDED_MIN_MARGIN,
} = require("../scripts/set-jisr-numbers.js");

/* مطابقة أسماء كشف جسر بسجلّ الموظفين.
   =========================================================================
   الأسماء في المصدرين لا تتطابق حرفيًا: الكشف يُخرج الاسم مُعادَ بناؤه
   من إحداثيات حروف الـPDF فيصل مشوّهًا، والسجلّ يحمل صيغة أخرى كتبها
   إنسان. النسخة الأولى من المطابق قاست اشتراك الحروف بلا ترتيب فتزاحمت
   أسماءٌ لا صلة بينها، وخرجت ثلاثة صفوف «غامضة» صحيحُها بيّن لعين
   بشرية. هذه الاختبارات تقيس تلك الحالات.

   ── البيانات مُعقَّمة ──
   الأسماء هنا وهمية بالكامل ولا تخصّ أحدًا. الأصل كان أسماء عشرة
   موظفين حقيقيين مأخوذة من كشف الرواتب وسجلّ الموظفين — وإبقاؤها كان
   يعني حفظ أسماء أشخاص في تاريخ Git للأبد ولكل من يستنسخ المستودع.

   وما نُقل عن الحالة الحقيقية ليس الأسماء بل **أنواع التشويه** بعينها،
   واحدًا واحدًا، وكل واحد منها يحمل رقم صفٍّ يقابله في العيّنة:

     محمد ↔ مد          17: «مد نظيف الاكرام» / «محمد نظيفال اكرام»
     أل التعريف مفصولة   16: «الرحيم» / «ال رحيم»
     تفكيك كلمة ودمجها   17: «نظيف الاكرام» / «نظيفال اكرام»
     اسم مختصر           18: «بشير عادل» / «بشير»  ·  20: «سامي فهد» / «سامي»
     صور الهمزة          12: «الأمجد» / «لامجد»
     تاء مربوطة وهاء     11: «راشة» / «راش»
     اختلاف إملائي       14: «منصير» / «منصر»
     كلمة مكرّرة         15: «وائل قاسم وائل» / «وائل قاسم»
     تزاحم على بداية     13 · 14 · 16 · 17 · 19 كلّها تبدأ بـ«مد»

   فما يُقاس هو الظاهرة نفسها التي أخفق عليها المطابق، لا الأشخاص.
   وأرقام ضمان في العيّنة 9xx لا 5xx، فلا يمكن لصفٍّ منها أن يشير إلى
   موظف حقيقي حتى بالخطأ. */

/* الكشف: رقم جسر + الاسم كما يُعاد بناؤه من إحداثيات حروف الـPDF. */
const SHEET = [
  { jisrNo: "11", nameHint: "نديم راشة" },
  { jisrNo: "12", nameHint: "الأمجد نوري" },
  { jisrNo: "13", nameHint: "مد سالم مد كريم" },
  { jisrNo: "14", nameHint: "مد وسيم منصير" },
  { jisrNo: "15", nameHint: "وائل قاسم وائل" },
  { jisrNo: "16", nameHint: "مد صابر الرحيم فهيم" },
  { jisrNo: "17", nameHint: "مد نظيف الاكرام" },
  { jisrNo: "18", nameHint: "بشير عادل" },
  { jisrNo: "19", nameHint: "مد هيثم مد الدين" },
  { jisrNo: "20", nameHint: "سامي فهد" },
];

/* السجلّ: رقم ضمان + الاسم. خمسة أسماء تبدأ بـ«مد» — وهو منشأ التزاحم. */
const EMPLOYEES = [
  { eid: "900", name: "بشير" },
  { eid: "901", name: "مد صابر ال رحيم فهيم" },
  { eid: "902", name: "مد سالم مد كريم" },
  { eid: "903", name: "وائل قاسم" },
  { eid: "904", name: "لامجد نوري" },
  { eid: "905", name: "محمد نظيفال اكرام" },
  { eid: "906", name: "نديم راش" },
  { eid: "907", name: "مد وسيم منصر" },
  { eid: "908", name: "سامي" },
  { eid: "909", name: "مد هيثم مد الدين" },
];

const assign = () => assignOneToOne(SHEET, EMPLOYEES, (r) => r.nameHint);
const byJisr = (results, jisrNo) => results.find((r) => r.row.jisrNo === jisrNo);

/* ── أنواع التشويه الثلاثة التي أخفقت ── */

test("انحدار: أل التعريف المفصولة — 16 → 901", () => {
  const r = byJisr(assign(), "16");
  assert.equal(r.employee && r.employee.eid, "901");
  assert.equal(r.decided, true);
  /* «الرحيم» في الكشف مقابل «ال رحيم» في السجلّ — وهي ما حسمت الصفّ. */
  assert.equal(similarity("مد صابر الرحيم فهيم", "مد صابر ال رحيم فهيم"), 1);
});

test("انحدار: محمد ↔ مد مع تفكيك كلمة — 17 → 905", () => {
  const r = byJisr(assign(), "17");
  assert.equal(r.employee && r.employee.eid, "905");
  assert.equal(r.decided, true);
  /* «محمد» ↔ «مد» تطبيعًا على مستوى الكلمة، و«نظيف الاكرام» مقابل
     «نظيفال اكرام» دمجًا لجزء من الكلمة التالية. */
  assert.ok(
    similarity("مد نظيف الاكرام", "محمد نظيفال اكرام") >
      similarity("مد نظيف الاكرام", "مد صابر ال رحيم فهيم"),
    "الاسم الصحيح يجب أن يسبق أقرب منافس يبدأ بـ«مد»"
  );
});

test("انحدار: الاسم المختصر — 18 → 900", () => {
  const r = byJisr(assign(), "18");
  assert.equal(r.employee && r.employee.eid, "900");
  assert.equal(r.decided, true);
  /* الاسم المختصر لا يُعاقَب على نقصه. */
  assert.equal(similarity("بشير عادل", "بشير"), 1);
  assert.ok(similarity("بشير عادل", "بشير") > similarity("بشير عادل", "مد سالم مد كريم"));
});

/* ── التفرّد: القاعدة التي طُلبت صراحةً ── */

test("لا رقم ضمان مُسنَد لأكثر من رقم جسر", () => {
  const eids = assign().filter((r) => r.employee).map((r) => r.employee.eid);
  assert.equal(new Set(eids).size, eids.length, "تكرار رقم ضمان يعني موظفًا مرّتين وآخر غائبًا");
});

test("العشرة كلها محسومة على العيّنة المُعقَّمة", () => {
  const results = assign();
  const undecided = results.filter((r) => !r.decided).map((r) => r.row.jisrNo);
  assert.deepEqual(undecided, [], `بقي غير محسوم: ${undecided.join(", ")}`);
  assert.deepEqual(
    results.map((r) => [r.row.jisrNo, r.employee.eid]),
    [["11","906"],["12","904"],["13","902"],["14","907"],["15","903"],
     ["16","901"],["17","905"],["18","900"],["19","909"],["20","908"]]
  );
});

/* الهامش يجب أن يبقى معتبرًا لا أن يمرّ بالكاد: صفٌّ يُحسم بهامش 0.21
   يمرّ اليوم ويصير غامضًا غدًا بأدنى تغيير في التطبيع. */
test("كل صفّ محسوم بهامش يفوق العتبة لا يلامسها", () => {
  for (const r of assign()) {
    assert.ok(r.margin >= DECIDED_MIN_MARGIN + 0.02,
      `جسر ${r.row.jisrNo} هامشه ${r.margin.toFixed(3)} — قريب من العتبة`);
  }
});

/* التخصيص عالميّ لا صفٌّ صفًّا: لو اختار كلٌّ أفضلَه وحده لتكرّر رقم.
   =========================================================================
   ⚠️ حدٌّ معروف في التغطية: هذا الاختبار يقيس أن اسمين متزاحمين على
   بداية واحدة يأخذ كلٌّ منهما نظيره — وهي النتيجة الصحيحة. لكنه لا يقيس
   خطوة التحسين بالتبديل الثنائي في assignOneToOne: بحثتُ في كل مجموعات
   العيّنة (حجم 2 إلى 4، رقمًا رقمًا) فلا واحدة يرفع فيها التبديل مجموع
   الدرجات فوق ما يبلغه الجشع التنازلي وحده — فتعطيل التبديل لا يُسقط
   اختبارًا. وكانت النسخة الأولى تحمل هذا الحدّ نفسه بلا تصريح.

   ولا يصحّ سدُّه باشتراط الأمثلية المطلقة: قِستُها بالقوّة الغاشمة على
   العيّنة، فوجدت أن «الأمثل» رياضيًا قد يكون إسنادًا خاطئًا تمامًا —
   «مد سالم مد كريم» يذهب إلى «سامي» بدرجة 0.75 ليتحرّر مرشّحه لصفّ آخر
   بدرجة 0.333، فيبلغ المجموع 1.083 بدل 1.0. والخوارزمية ترفض ذلك وهي
   محقّة. فهي ليست Hungarian ولا تدّعي الأمثلية، والحاجز الحقيقي هو
   التفرّد وعتبة الحسم — وكلاهما مقيس أعلاه. */
test("التخصيص يفضّل نظير كل اسم لا أن يستأثر الأقوى بالمرشّح المشترك", () => {
  const rows = [{ jisrNo: "1", nameHint: "مد هيثم مد الدين" }, { jisrNo: "2", nameHint: "مد سالم مد كريم" }];
  const emps = [{ eid: "909", name: "مد هيثم مد الدين" }, { eid: "902", name: "مد سالم مد كريم" }];
  const res = assignOneToOne(rows, emps, (r) => r.nameHint);
  assert.equal(res[0].employee.eid, "909");
  assert.equal(res[1].employee.eid, "902");
});

/* ── لا تخمين إجباري ── */

test("اسم لا نظير له يبقى «غير محسوم» بلا رقم ضمان", () => {
  const rows = [{ jisrNo: "999", nameHint: "غيداء مبارك الفهيد" }];
  const res = assignOneToOne(rows, EMPLOYEES, (r) => r.nameHint);
  assert.equal(res[0].decided, false);
  assert.equal(res[0].employee, null, "لا يُملأ بأقرب موجود");
});

test("صفوف أكثر من الموظفين: الزائد غير محسوم لا مُسنَد بالقوّة", () => {
  const rows = [{ jisrNo: "1", nameHint: "بشير عادل" }, { jisrNo: "2", nameHint: "بشير عادل" }];
  const res = assignOneToOne(rows, [{ eid: "900", name: "بشير" }], (r) => r.nameHint);
  const decided = res.filter((r) => r.employee);
  assert.equal(decided.length, 1, "رقم ضمان واحد لا يُسنَد لصفّين");
});

test("العتبتان معلَنتان ومعقولتان", () => {
  assert.ok(DECIDED_MIN_SCORE > 0.5 && DECIDED_MIN_SCORE <= 0.7);
  assert.ok(DECIDED_MIN_MARGIN >= 0.15);
});

/* ── التطبيع: لا \b على العربية ── */

test("التقسيم على المسافات لا على حدود ASCII", () => {
  /* \bمحمد\b لا يطابق شيئًا في نصّ عربي — هذا العطل بعينه أبقى صفّ
     «محمد» غامضًا. */
  assert.deepEqual(nameTokens("محمد نظيفال اكرام"), ["مد", "نظيفال", "اكرام"]);
  assert.deepEqual(nameTokens("مد صابر ال رحيم فهيم"), ["مد", "صابر", "رحيم", "فهيم"]);
  assert.deepEqual(nameTokens("مد نظيف الاكرام"), ["مد", "نظيف", "اكرام"]);
});

test("طيّ صور الهمزة والتاء المربوطة", () => {
  assert.equal(foldArabic("الأمجد"), foldArabic("الامجد"));
  assert.equal(foldArabic("راشة"), foldArabic("راشه"));
  assert.ok(similarity("الأمجد نوري", "لامجد نوري") >= 0.9);
});

test("أل التعريف لا تُحذف من كلمة قصيرة فتُشوَّه", () => {
  assert.deepEqual(nameTokens("الي"), ["الي"], "ثلاثة أحرف تبقى كما هي");
  assert.deepEqual(nameTokens("الاكرام"), ["اكرام"]);
});

test("تقارب الكلمة يشترط عتبة: الضعيف صفر لا درجة صغيرة", () => {
  assert.equal(tokenMatch("مد", "مد"), 1);
  assert.ok(tokenMatch("منصر", "منصير") >= 0.7, "اختلاف إملائي يُقبل");
  assert.equal(tokenMatch("نديم", "فهد"), 0, "كلمتان مختلفتان لا تُعطيان درجة");
});

/* البداية المشتركة قاعدةٌ مستقلّة عن التساوي وعن التقارب الإملائي، وهي
   وحدها ما يُنقذ «نظيف» ↔ «نظيفال»: تقاربهما الإملائي 4/6 = 0.67 دون
   العتبة، فبلا هذه القاعدة تصير درجتهما صفرًا.

   كُتب هذا الاختبار لأن النسخة الأولى منه قاست «بشير» مع «بشير» —
   وذلك تساوٍ لا بداية مشتركة، فكانت تمرّ ولو أُزيلت القاعدة كليًّا. */
test("البداية المشتركة قاعدة قائمة بذاتها لا فرعٌ عن التساوي", () => {
  assert.equal(tokenMatch("نظيف", "نظيفال"), 0.95, "أقصر يبدأ الأطول");
  assert.equal(tokenMatch("راشه", "راش"), 0.95, "والعكس");
  /* والدليل أنها ليست تقاربًا إملائيًا: النسبة وحدها دون العتبة. */
  assert.ok(4 / 6 < 0.7, "تقارب «نظيف/نظيفال» الإملائي وحده لا يكفي");
});

test("اسم فارغ أو بلا حروف عربية درجته صفر", () => {
  for (const v of ["", "   ", null, undefined, "12345", "abc"]) {
    assert.equal(similarity(v, "بشير"), 0);
    assert.equal(similarity("بشير", v), 0);
  }
});

/* حاجز السياسة: لا اسم من أسماء الموظفين الحقيقيين في هذا الملفّ. */
test("العيّنة خالية من أسماء الموظفين الحقيقيين وأرقام ضمانهم", () => {
  const names = [...SHEET.map((r) => r.nameHint), ...EMPLOYEES.map((e) => e.name)].join(" ");
  /* أرقام ضمان الحقيقية في المدى 5xx — العيّنة كلها 9xx. */
  for (const e of EMPLOYEES) assert.match(e.eid, /^9\d\d$/);
  /* وأرقام جسر الحقيقية من 49 إلى 85 — العيّنة 11–20. */
  for (const r of SHEET) assert.ok(Number(r.jisrNo) >= 11 && Number(r.jisrNo) <= 20);
  /* ولا رقم إقامة ولا IBAN في أي حال. */
  assert.equal(/(?<!\d)2\d{9}(?!\d)/.test(names), false);
  assert.equal(/SA\d{22}/.test(names), false);
});
