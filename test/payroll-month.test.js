const test = require("node:test");
const assert = require("node:assert/strict");

const { previousMonthRun, snapshotOf, CATCH_UP_DAYS } = require("../lib/payroll/monthlyRun");

/* اشتقاق شهر المسير — الشهر السابق دائمًا، بتوقيت Asia/Riyadh.
   =========================================================================
   الحدود هي كل شيء هنا. المنصّة تعمل على UTC+3 بلا توقيت صيفي، والـCron
   يُطلق عند 03:00 UTC أي السادسة صباحًا بالرياض. اشتقاق الشهر من UTC
   مباشرةً كان سيجعل مساء اليوم الأخير من الشهر يقع في الشهر التالي —
   وهو بالضبط الخطأ الذي ينتج مسيرًا لشهر خاطئ مرّة كل سنة أو سنتين. */

test("أول سبتمبر ينشئ مسير أغسطس لا سبتمبر", () => {
  const r = previousMonthRun(new Date("2026-09-01T03:00:00Z"));
  assert.equal(r.id, "2026-08");
  assert.equal(r.monthLabel, "أغسطس 2026");
});

test("أول يناير يرجع إلى ديسمبر السنة الماضية", () => {
  const r = previousMonthRun(new Date("2026-01-01T03:00:00Z"));
  assert.equal(r.id, "2025-12");
  assert.equal(r.monthLabel, "ديسمبر 2025");
});

/* 21:30Z من 31 أغسطس = 00:30 من 1 سبتمبر بالرياض — يومٌ جديد وشهرٌ
   جديد، فالمسير المستحقّ هو أغسطس. من يحسب بـUTC يرى 31 أغسطس فيشتقّ
   يوليو: مسير شهر كامل خطأ. */
test("منتصف ليل الرياض قبل منتصف ليل UTC: الشهر يتقدّم صحيحًا", () => {
  const r = previousMonthRun(new Date("2026-08-31T21:30:00Z"));
  assert.equal(r.id, "2026-08");
  assert.equal(r.createdOn, "2026-09-01");
});

/* 20:00Z من 31 أغسطس = 23:00 من 31 أغسطس بالرياض — ما زال اليوم الأخير
   من الشهر، خارج نافذة التدارك تمامًا. */
test("مساء اليوم الأخير من الشهر ما زال في الشهر نفسه بالرياض", () => {
  const r = previousMonthRun(new Date("2026-08-31T20:00:00Z"));
  assert.equal(r.createdOn, "2026-08-31");
  assert.ok(31 > CATCH_UP_DAYS, "اليوم 31 خارج نافذة التدارك");
});

test("أسماء الأشهر كلها بالعربي", () => {
  const labels = [];
  for (let m = 1; m <= 12; m++) {
    labels.push(previousMonthRun(new Date(Date.UTC(2026, m, 1, 3, 0, 0))).monthLabel);
  }
  assert.deepEqual(labels, [
    "يناير 2026", "فبراير 2026", "مارس 2026", "أبريل 2026", "مايو 2026", "يونيو 2026",
    "يوليو 2026", "أغسطس 2026", "سبتمبر 2026", "أكتوبر 2026", "نوفمبر 2026", "ديسمبر 2026",
  ]);
  for (const l of labels) assert.ok(!/[A-Za-z]/.test(l), `${l} يحوي حروفًا لاتينية`);
});

/* اللقطة تحمي من سجلّ ناقص أو مكرّر قبل أن يصل إلى القاعدة. */
test("اللقطة تُسقط السجلّات الناقصة وتزيل التكرار", () => {
  const snap = snapshotOf([
    { "الرقم الوظيفي": "1001", "اسم العامل": "أحمد علي", "المهنة": "سائق" },
    { "الرقم الوظيفي": "1001", "اسم العامل": "أحمد علي مكرّر" },
    { "الرقم الوظيفي": "", "اسم العامل": "بلا رقم" },
    { "الرقم الوظيفي": "1002", "اسم العامل": "" },
    { "الرقم الوظيفي": "1003", "اسم العامل": "سعيد محمد" },
  ]);
  assert.deepEqual(snap, [
    { eid: "1001", name: "أحمد علي", jobTitle: "سائق" },
    { eid: "1003", name: "سعيد محمد", jobTitle: null },
  ]);
});
